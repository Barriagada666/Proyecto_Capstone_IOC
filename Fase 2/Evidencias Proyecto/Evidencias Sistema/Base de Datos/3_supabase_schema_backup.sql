--
-- Name: login_with_roles(text, text); Type: FUNCTION; Schema: public; Owner: postgres
--

CREATE FUNCTION public.login_with_roles(email_input text, password_input text) RETURNS json
    LANGUAGE plpgsql
    AS $$
DECLARE
    -- Variables para almacenar datos del usuario y roles
    user_record RECORD;
    user_roles TEXT[];
    claims JSONB;
    new_token TEXT;
BEGIN
    -- 1. Buscar al usuario por su email en la tabla de autenticación de Supabase
    SELECT * INTO user_record FROM auth.users WHERE email = email_input;

    -- 2. Si no se encuentra el usuario, devolver un error
    IF user_record IS NULL THEN
        RAISE EXCEPTION 'Invalid login credentials';
    END IF;

    -- 3. Verificar la contraseña usando la función crypt de pgcrypto
    --    Compara la contraseña proporcionada con el hash almacenado en Supabase
    IF user_record.encrypted_password != crypt(password_input, user_record.encrypted_password) THEN
        RAISE EXCEPTION 'Invalid login credentials';
    END IF;

    -- 4. Si las credenciales son correctas, obtener los roles del usuario.
    --    ¡¡IMPORTANTE!! Esta consulta asume que tienes una tabla que relaciona
    --    usuarios con roles. Debes adaptarla a tu esquema.
    --    Ejemplo: SELECT r.name INTO user_roles FROM user_roles ur JOIN roles r ON ur.role_id = r.id WHERE ur.user_id = user_record.id;
    --
    --    Por ahora, asignaremos roles de ejemplo.
    --    DESCOMENTA Y ADAPTA LA LÍNEA REAL CUANDO TENGAS TUS TABLAS DE ROLES.
    --
    user_roles := ARRAY['ROLE_USER', 'ROLE_VIEWER']; -- <-- VALOR DE EJEMPLO

    -- 5. Construir los 'claims' (el contenido) del nuevo JWT.
    --    Incluimos los claims estándar de Supabase y añadimos nuestro claim personalizado 'roles'.
    claims := jsonb_build_object(
        'sub', user_record.id,
        'aud', 'authenticated',
        'role', 'authenticated',
        'exp', extract(epoch from now() at time zone 'utc') + (60*60), -- Expira en 1 hora
        'roles', user_roles -- <-- NUESTRO CLAIM PERSONALIZADO
    );

    -- 6. Firmar el nuevo token usando el secreto JWT de tu proyecto.
    new_token := extensions.sign(claims, current_setting('app.settings.jwt_secret'));

    -- 7. Devolver el nuevo token en un objeto JSON.
    RETURN json_build_object('access_token', new_token);
END;
$$;



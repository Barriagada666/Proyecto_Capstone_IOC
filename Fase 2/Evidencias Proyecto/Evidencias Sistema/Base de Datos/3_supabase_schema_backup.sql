CREATE FUNCTION public.cleanup_idle_metabase_connections() RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    AS $$
DECLARE
  closed_count int;
BEGIN
  SELECT COUNT(*) INTO closed_count
  FROM pg_stat_activity 
  WHERE datname = 'postgres'
    AND application_name LIKE '%Metabase%'
    AND state = 'idle'
    AND backend_start < NOW() - INTERVAL '10 minutes'
    AND pid != pg_backend_pid();
  
  -- Cerrar las conexiones
  PERFORM pg_terminate_backend(pid)
  FROM pg_stat_activity 
  WHERE datname = 'postgres'
    AND application_name LIKE '%Metabase%'
    AND state = 'idle'
    AND backend_start < NOW() - INTERVAL '10 minutes'
    AND pid != pg_backend_pid();
  
  RAISE NOTICE 'Cerradas % conexiones idle de Metabase', closed_count;
END;
$$;


